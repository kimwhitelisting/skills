export const PX_FOODS = Object.keys(MAPS);

export function food(id: string): Grid {
  const g = new Grid(16, 16);
  const rows = MAPS[id];
  g.stamp(rows, 0, Math.floor((16 - rows.length) / 2) + 1, pal);
  return g.outline(P.ink);
}
